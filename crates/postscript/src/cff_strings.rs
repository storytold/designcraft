/// SIDs 379–390.
const TAIL: [&str; 12] = ["001.000", "001.001", "001.002", "001.003", "Black", "Bold", "Book", "Light", "Medium", "Regular", "Roman", "Semibold"];

/// The number of standard strings.
pub const COUNT: usize = 391;

/// The glyph name a standard SID stands for. The expert-set names (229–378) are given as
/// `sid<n>`, which only has to be consistent within one font (they are its own glyph names).
pub fn standard(sid: usize) -> Option<String> {
    if let Some(n) = NAMES.get(sid) {
        return Some((*n).to_string());
    }
    if let Some(n) = sid.checked_sub(379).and_then(|i| TAIL.get(i)) {
        return Some((*n).to_string());
    }
    (sid < COUNT).then(|| format!("sid{sid}"))
}
