pub fn standard() -> Vec<&'static str> {
    let mut v = vec![".notdef"; 256];
    for (i, n) in ASCII.iter().enumerate() {
        if let Some(slot) = v.get_mut(32 + i) {
            *slot = n;
        }
    }
    for (c, n) in STANDARD_HIGH {
        if let Some(slot) = v.get_mut(usize::from(*c)) {
            *slot = n;
        }
    }
    v
}

pub fn iso_latin1() -> Vec<&'static str> {
    let mut v = vec![".notdef"; 256];
    for (i, n) in ASCII.iter().enumerate() {
        if let Some(slot) = v.get_mut(32 + i) {
            *slot = n;
        }
    }
    // Latin-1 differs from Standard at the minus sign.
    if let Some(slot) = v.get_mut(45) {
        *slot = "minus";
    }
    for (i, n) in LATIN1_HIGH.iter().enumerate() {
        if let Some(slot) = v.get_mut(144 + i) {
            *slot = n;
        }
    }
    v
}

#[cfg(test)]
mod tests {
    #[test]
    fn encodings_place_their_glyphs() {
        let s = super::standard();
        assert_eq!((s[65], s[39], s[251], s[200]), ("A", "quoteright", "germandbls", "dieresis"));
        let l = super::iso_latin1();
        assert_eq!((l[228], l[45], l[173], l[223], l[255]), ("adieresis", "minus", "hyphen", "germandbls", "ydieresis"));
    }
}
