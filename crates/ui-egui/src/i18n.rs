/// Interface direction; independent of document binding and paragraph direction.
pub fn is_rtl(lang: &str) -> bool {
    lang == "ar"
}

fn column(lang: &str) -> Option<usize> {
    match lang {
        "de" => Some(0),
        "fr" => Some(1),
        "es" => Some(2),
        _ => None,
    }
}

/// The script whose letterforms the interface prefers for Han characters, Kana and Hangul:
/// "Jpan", "Hans", "Hant" or "Kore" (`theme` orders the CJK fallback faces by it). Languages
/// without a CJK preference use Japanese forms, the app's default CJK face.
pub fn cjk_script(lang: &str) -> &'static str {
    match lang {
        "zh" => "Hans",
        "zh-hant" => "Hant",
        "ko" => "Kore",
        _ => "Jpan",
    }
}

/// The one-string-per-language tables (Arabic, Brazilian Portuguese, Japanese, Chinese, Korean).
fn single(lang: &str) -> Option<&'static HashMap<&'static str, &'static str>> {
    type Map = OnceLock<HashMap<&'static str, &'static str>>;
    static MAPS: [Map; 6] = [Map::new(), Map::new(), Map::new(), Map::new(), Map::new(), Map::new()];
    let (i, table) = match lang {
        "ar" => (0, ar::TABLE),
        "pt-br" => (1, pt_br::TABLE),
        "ja" => (2, ja::TABLE),
        "zh" => (3, zh_hans::TABLE),
        "zh-hant" => (4, zh_hant::TABLE),
        "ko" => (5, ko::TABLE),
        _ => return None,
    };
    Some(MAPS.get(i)?.get_or_init(|| table.iter().copied().collect()))
}

/// `s` in `lang` (English, or the string itself, when there's no translation).
pub fn tr<'a>(lang: &str, s: &'a str) -> &'a str {
    static TRANSLATIONS: OnceLock<HashMap<&'static str, [&'static str; 3]>> = OnceLock::new();
    if let Some(map) = single(lang) {
        return map.get(s).copied().unwrap_or(s);
    }
    let Some(c) = column(lang) else { return s };
    TRANSLATIONS.get_or_init(|| TABLE.iter().copied().collect()).get(s).and_then(|row| row.get(c)).copied().unwrap_or(s)
}

/// Whether `lang` has its own entry for `s` (for the coverage tests; the entry may equal the
/// English, as product names and units do).
#[cfg(test)]
pub(crate) fn has_entry(lang: &str, s: &str) -> bool {
    single(lang).is_some_and(|m| m.contains_key(s))
}

/// Localize reserved built-in style names only; user-defined names are document data.
pub fn style_name<'a>(lang: &str, name: &'a str) -> &'a str {
    match name {
        designcraft_doc::NO_PARA_STYLE | designcraft_doc::BASIC_PARAGRAPH | designcraft_doc::NO_CHAR_STYLE => tr(lang, name),
        _ => name,
    }
}

/// Built-in workspace captions; custom workspace names remain unchanged.
pub fn workspace_name<'a>(lang: &str, name: &'a str) -> &'a str {
    match name {
        "Essentials" | "Advanced" | "Book" | "Digital Publishing" | "Interactive for PDF" | "Printing and Proofing" | "Typography" => tr(lang, name),
        _ => name,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn single_tables() -> [(&'static str, &'static [(&'static str, &'static str)]); 6] {
        [("ar", ar::TABLE), ("pt-br", pt_br::TABLE), ("ja", ja::TABLE), ("zh", zh_hans::TABLE), ("zh-hant", zh_hant::TABLE), ("ko", ko::TABLE)]
    }

    #[test]
    fn cached_lookup_preserves_every_translation_across_language_switches() {
        for (key, translations) in TABLE {
            for (lang, expected) in ["de", "fr", "es"].into_iter().zip(translations) {
                assert_eq!(tr(lang, key), *expected, "{lang}: {key}");
            }
            assert_eq!(tr("", key), *key);
        }
        for (lang, table) in single_tables() {
            for (key, expected) in table {
                assert_eq!(tr(lang, key), *expected, "{lang}: {key}");
            }
        }
        let unknown = String::from("A user-defined untranslated label");
        for lang in ["ar", "pt-br", "zh", "zh-hant", "ko", "ja", "de", "fr", "es", "", "unknown"] {
            assert!(std::ptr::eq(tr(lang, &unknown), unknown.as_str()));
        }
    }

    #[test]
    fn translates_known_strings_and_keeps_the_rest() {
        assert_eq!(tr("de", "File"), "Datei");
        assert_eq!(tr("ja", "Swatches"), "スウォッチ");
        assert_eq!(tr("fr", "Something new"), "Something new");
        assert_eq!(tr("", "File"), "File");
        assert_eq!(tr("ar", "File"), "ملف");
        assert_eq!(tr("ar", "Unknown label"), "Unknown label");
        assert_eq!(tr("pt-br", "File"), "Arquivo");
        assert_eq!(tr("pt-br", "New Document…"), "Novo documento…");
        assert_eq!(tr("pt-br", "Unknown label"), "Unknown label");
        assert!(is_rtl("ar"));
        for (lang, table) in single_tables() {
            let mut seen = std::collections::HashSet::new();
            for (en, translation) in table {
                assert!(seen.insert(*en), "{lang}: duplicate {en}");
                assert!(!translation.is_empty(), "{lang}: {en}");
            }
        }
        // Every row is unique and complete.
        for (i, (en, t)) in TABLE.iter().enumerate() {
            assert!(TABLE[..i].iter().all(|(e, _)| e != en), "duplicate {en}");
            assert!(t.iter().all(|x| !x.is_empty()), "{en}");
        }
    }

    #[test]
    fn japanese_vertical_type_commands_are_translated() {
        for (en, ja) in [
            ("Story Direction", "組み方向"),
            ("Horizontal", "横書き"),
            ("Vertical", "縦書き"),
            ("Tate-Chu-Yoko", "縦中横"),
            ("Ruby…", "ルビ…"),
            ("Kenten", "圏点"),
        ] {
            assert_eq!(tr("ja", en), ja);
        }
    }
}
